// Детектор мошеннических формулировок в комментарии к переводу (RU + KZ).
// В проде — дообучаемый классификатор / LLM; здесь — прозрачные правила для объяснимости.
// Важно: флаг `u` + \p{L}, т.к. \w и \b в JS не работают с кириллицей.

const L = '\\p{L}';
const rx = (src) => new RegExp(src.replace(/\\L/g, L), 'iu');

const PATTERNS = [
  { cat: 'Фраза «безопасный счёт» / «служба безопасности»', points: 25,
    re: rx('безопасн\\L*\\s+сч[её]т|служб\\L*\\s+безопасност|сотрудник\\L*\\s+банка|резервн\\L*\\s+сч[её]т|қауіпсіз\\s+шот|қауіпсіздік\\s+қызмет') },
  { cat: 'Упоминание SMS-кода / CVV', points: 25,
    re: rx('код\\L*\\s*(из\\s*)?смс|sms[\\s-]?код|смс[\\s-]?код|cvv|cvc') },
  { cat: 'Ссылка на полицию / КНБ / следователя', points: 20,
    re: rx('полици|кнб|прокурат|следовател|финпол|ұлттық\\s+қауіпсіздік') },
  { cat: 'Предоплата / маркетплейс', points: 12,
    re: rx('предоплат|задат|olx|доставк|бронь|аренд') },
  { cat: 'Инвестиции / крипто / «доход»', points: 15,
    re: rx('инвест|крипт|usdt|бирж|доход|пассивн|ставк|казино|трейд') },
  { cat: 'Выигрыш / приз / компенсация', points: 15,
    re: rx('выигр|приз|розыгрыш|лотере|компенсац|ұтыс|сыйлық') },
  { cat: 'Давление срочностью', points: 8,
    re: rx('срочно|немедленно|прямо\\s+сейчас|шұғыл|тез арада') },
  { cat: '«Родственник в беде»', points: 12,
    re: rx('попал\\L*\\s+в|авари|дтп|больниц|выручи|займи|адвокат') },
];

function analyzeText(text = '') {
  const hits = [];
  if (!text) return { points: 0, hits };
  for (const p of PATTERNS) if (p.re.test(text)) hits.push({ cat: p.cat, points: p.points });
  const points = Math.min(40, hits.reduce((s, h) => s + h.points, 0));
  return { points, hits };
}

module.exports = { analyzeText };
