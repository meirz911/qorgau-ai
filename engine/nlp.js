const tokenize = (s) => (s.toLowerCase().match(/[\p{L}\d]+/gu) || [])
  .filter((t) => t.length > 1)
  .flatMap((t) => [t, t.slice(0, 5)]); // слово + основа (первые 5 букв) — простой стемминг для RU/KZ

class NaiveBayes {
  constructor() {
    this.counts = { scam: new Map(), legit: new Map() };
    this.totals = { scam: 0, legit: 0 };
    this.docs = { scam: 0, legit: 0 };
    this.vocab = new Set();
  }

  add(text, cls) {
    this.docs[cls]++;
    for (const t of tokenize(text)) {
      this.counts[cls].set(t, (this.counts[cls].get(t) || 0) + 1);
      this.totals[cls]++;
      this.vocab.add(t);
    }
  }

  // Вероятность того, что текст — мошеннический (0..1), и самые «скамовые» слова
  predict(text) {
    const toks = tokenize(text);
    if (!toks.length) return { prob: 0, words: [] };
    const V = this.vocab.size;
    let ls = Math.log(this.docs.scam / (this.docs.scam + this.docs.legit));
    let ll = Math.log(this.docs.legit / (this.docs.scam + this.docs.legit));
    const contrib = [];
    for (const t of toks) {
      if (!this.vocab.has(t)) continue;
      const ps = Math.log(((this.counts.scam.get(t) || 0) + 1) / (this.totals.scam + V));
      const pl = Math.log(((this.counts.legit.get(t) || 0) + 1) / (this.totals.legit + V));
      ls += ps; ll += pl;
      contrib.push({ t, d: ps - pl });
    }
    const prob = 1 / (1 + Math.exp(ll - ls));
    const cand = [...new Set(contrib.filter((c) => c.d > 0.7 && c.t.length > 3).sort((a, b) => b.d - a.d).map((c) => c.t))];
    // убираем основы-дубликаты: «срочн» при наличии «срочно»
    const words = cand.filter((w) => !cand.some((o) => o !== w && o.startsWith(w))).slice(0, 4);
    return { prob, words };
  }
}

